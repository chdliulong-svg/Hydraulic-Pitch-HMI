# Secondary lookup index by name
ALARM_BY_NAME: dict[str, AlarmDefinition] = {d.name: d for d in ALARM_DATABASE.values()}


def get_alarm_def(code: int) -> AlarmDefinition:
    """Retrieve alarm metadata by numeric code with O(1) complexity and safe fallback."""
    if code in ALARM_DATABASE:
        return ALARM_DATABASE[code]
    return AlarmDefinition(
        code=code,
        name=f"Alarm_{code}",
        message_en=f"Unknown alarm code {code}",
        message_cn=f"未知报警代码 {code}",
        severity=50,
    )


def get_alarm_by_name(name: str) -> AlarmDefinition:
    """Retrieve alarm metadata by unique string identifier."""
    if name in ALARM_BY_NAME:
        return ALARM_BY_NAME[name]
    return AlarmDefinition(
        code=0,
        name=name,
        message_en=f"Alarm {name}",
        message_cn=f"报警 {name}",
        severity=50,
    )
