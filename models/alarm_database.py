# Runtime limit values dynamically populated purely from OPC UA (PVAlarms.limitSet)
RUNTIME_PV_LIMITS: dict[str, float] = {}
RUNTIME_PV_STRINGS: dict[str, str] = {"networkConfigError": ""}


def update_pv_alarm_limits(limits: dict[str, float]):
    """Update runtime limits read from OPC UA PVAlarms.limitSet"""
    RUNTIME_PV_LIMITS.update(limits)


def update_pv_alarm_strings(strings: dict[str, str]):
    """Update runtime dynamic strings (e.g. networkErrMsg)"""
    RUNTIME_PV_STRINGS.update(strings)


def get_pv_limit(field: str) -> Optional[float]:
    return RUNTIME_PV_LIMITS.get(field)


@dataclass(frozen=True)
class AlarmDefinition:
    code: int
    name: str
    message_en: str
    message_cn: str
    severity: int  # 50: Warning/Notice, 100: Normal, 200: Severe/Error, 300: Critical Safety Stop
    pv_field: Optional[str] = None
    format_spec: str = "4.1f"

    def get_message(self, lang: str = "EN") -> str:
        base = self.message_cn if (lang and lang.upper() in ["CN", "ZH"]) else self.message_en
        if not self.pv_field:
            return base

        # 1. Float limit substitution from PVAlarms.limitSet
        if self.pv_field in RUNTIME_PV_LIMITS:
            val = RUNTIME_PV_LIMITS[self.pv_field]
            val_str = f"{val:4.1f}".strip()
            if "{val}" in base:
                return base.replace("{val}", val_str)

        # 2. String substitution (e.g. networkErrMsg)
        if self.pv_field in RUNTIME_PV_STRINGS:
            s_val = RUNTIME_PV_STRINGS[self.pv_field]
            val_str = f": {s_val}" if s_val else ""
            if "{val}" in base:
                return base.replace("{val}", val_str)

        # Fallback if not yet read from OPC UA
        return base.replace("{val}", "---")


